// ignore_for_file: avoid_print
import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:xml/xml.dart';

import 'file_edit.dart';

/// Exit codes returned by setup operations.
enum SetupExitCode {
  /// Success or no-op.
  ok,

  /// An unrecoverable error occurred.
  error,

  /// A manual action is needed; setup was skipped for safety.
  manualActionNeeded,
}

/// Result of a single setup action.
class SetupActionResult {
  /// Creates a [SetupActionResult].
  const SetupActionResult({
    required this.exitCode,
    required this.message,
  });

  /// Outcome of the action.
  final SetupExitCode exitCode;

  /// Human-readable description suitable for console output.
  final String message;

  /// Returns `true` when this action made or would make a change.
  ///
  /// Pass [isDryRun] as `true` to detect intended-but-not-written changes.
  bool didChange({required bool isDryRun}) {
    if (isDryRun) {
      return message.contains('would');
    }
    return exitCode == SetupExitCode.ok && !message.contains('already');
  }
}

const String _langswitchMarker = '<!-- generated by langswitch -->';

/// Performs the Android per-app language setup on a Flutter project.
class AndroidSetup {
  /// Creates an [AndroidSetup] for the project at [projectRoot].
  AndroidSetup(this.projectRoot, {required this.editor});

  /// Absolute path to the Flutter project root.
  final String projectRoot;

  /// File editor (may be a dry-run editor).
  final FileEditor editor;

  /// Creates or updates `android/app/src/main/res/xml/locales_config.xml`
  /// and patches `android/app/src/main/AndroidManifest.xml`.
  List<SetupActionResult> run(List<String> locales) {
    return [
      _setupLocalesConfig(locales),
      _setupManifest(),
    ];
  }

  SetupActionResult _setupLocalesConfig(List<String> locales) {
    final xmlPath = p.join(
      projectRoot,
      'android',
      'app',
      'src',
      'main',
      'res',
      'xml',
      'locales_config.xml',
    );

    final existing = editor.read(xmlPath);
    if (existing.isNotEmpty && !existing.contains(_langswitchMarker)) {
      return const SetupActionResult(
        exitCode: SetupExitCode.manualActionNeeded,
        message: 'android/app/src/main/res/xml/locales_config.xml already '
            'exists and was not created by langswitch. Add the missing '
            '<locale> entries manually and re-run with --check to verify.',
      );
    }

    final buf = StringBuffer();
    buf.writeln('<?xml version="1.0" encoding="utf-8"?>');
    buf.writeln(_langswitchMarker);
    buf.writeln(
        '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">');
    for (final tag in locales) {
      buf.writeln('    <locale android:name="$tag"/>');
    }
    buf.writeln('</locale-config>');

    final result = editor.write(xmlPath, buf.toString());
    if (!result.changed) {
      return const SetupActionResult(
        exitCode: SetupExitCode.ok,
        message: 'Android: locales_config.xml already up to date.',
      );
    }
    return SetupActionResult(
      exitCode: SetupExitCode.ok,
      message:
          'Android: locales_config.xml ${editor.dryRun ? 'would be created' : 'created'} '
          '(${locales.length} locales).',
    );
  }

  SetupActionResult _setupManifest() {
    final manifestPath = p.join(
      projectRoot,
      'android',
      'app',
      'src',
      'main',
      'AndroidManifest.xml',
    );

    final file = File(manifestPath);
    if (!file.existsSync()) {
      return const SetupActionResult(
        exitCode: SetupExitCode.error,
        message: 'Could not find android/app/src/main/AndroidManifest.xml. '
            'Run from the Flutter project root.',
      );
    }

    final content = file.readAsStringSync();

    // Parse to check for existing localeConfig.
    XmlDocument doc;
    try {
      doc = XmlDocument.parse(content);
    } on XmlParserException catch (e) {
      return SetupActionResult(
        exitCode: SetupExitCode.error,
        message: 'Failed to parse AndroidManifest.xml: $e',
      );
    }

    final appElements = doc.findAllElements('application').toList();
    if (appElements.isEmpty) {
      return const SetupActionResult(
        exitCode: SetupExitCode.error,
        message: 'No <application> element found in AndroidManifest.xml.',
      );
    }

    final appElement = appElements.first;
    final existingLocaleConfig =
        appElement.getAttribute('android:localeConfig');

    if (existingLocaleConfig != null &&
        existingLocaleConfig != '@xml/locales_config') {
      return SetupActionResult(
        exitCode: SetupExitCode.manualActionNeeded,
        message:
            'AndroidManifest.xml already has android:localeConfig="$existingLocaleConfig". '
            'langswitch expected "@xml/locales_config". Update manually if '
            'needed and re-run with --check.',
      );
    }

    if (existingLocaleConfig == '@xml/locales_config') {
      return const SetupActionResult(
        exitCode: SetupExitCode.ok,
        message: 'Android: manifest android:localeConfig already set.',
      );
    }

    // Insert android:localeConfig using targeted text replacement so that
    // formatting, comments, and other attributes are preserved.
    final newContent = _insertLocaleConfigAttribute(content);
    if (newContent == null) {
      return const SetupActionResult(
        exitCode: SetupExitCode.error,
        message:
            'Could not locate <application in AndroidManifest.xml to insert '
            'android:localeConfig. Add it manually.',
      );
    }

    final result = editor.write(manifestPath, newContent);
    if (!result.changed) {
      return const SetupActionResult(
        exitCode: SetupExitCode.ok,
        message: 'Android: manifest already up to date.',
      );
    }
    return SetupActionResult(
      exitCode: SetupExitCode.ok,
      message:
          'Android: ${editor.dryRun ? 'would add' : 'added'} android:localeConfig to manifest.',
    );
  }

  String? _insertLocaleConfigAttribute(String content) {
    // Find <application and insert the attribute before the closing > or first \.
    final appTagPattern =
        RegExp(r'(<application\b[^>]*?)(\s*/?>)', dotAll: true);
    final match = appTagPattern.firstMatch(content);
    if (match == null) return null;

    final before = match.group(1)!;
    final after = match.group(2)!;
    const attr = '\n        android:localeConfig="@xml/locales_config"';

    return content.replaceFirst(match.group(0)!, '$before$attr$after');
  }
}
